import { defineConfig, devices } from '@playwright/test';
import { withTierFilters } from './utils/regression/projectFilters';
import { prepareRun } from './utils/regression/runEnv';

// Env file (REG_ENV_FILE, else API_ENV_FILE, else ./.env; never the cwd .env once one is named; a named file must exist),
// TIER_KIND / AUTH_MODE / REG_RA_PROFILE_NAME frozen, one run id for both suites (API_RUN_ID = REG_RUN_ID), API_DELETE_OWN
// default, the run's cleanup ledger, the TIER_KIND=local proof (local BASE_URL + REG_LOCAL_CORE_URL with a build marker +
// a container publishing the core port), header auth only on a local BASE_URL, one worker, and the run lock. Any failure
// stops the run before a test is listed (utils/regression/runEnv.ts).
prepareRun({ configDir: __dirname });

/**
 * API coverage suite (API-*): one spec per task, positive and negative cases, generated by qa-api-coverage and completed
 * by hand. No globalSetup (the smoke PKI chain is not needed); the `gate` project has a browser for its one UI sentinel.
 *
 * Shared tiers: tests read, create run-prefixed objects (recorded in the ledger before any assertion) and change only
 * objects they created: mutations go through the guarded `api` fixture or `getGuardedApiContext(request, env, opts?)`
 * (utils/regression/guardedApi.ts: ledger line of this run + live run-prefixed name for every uuid the request names,
 * path and body associations) or the own-object helpers (`assertOwnLive`); deny by default, linted by
 * tests/unit/specGuards.spec.ts. Pre-existing
 * objects are never changed or deleted (decision Q1). Everything the run created is deleted at the end by `runTeardown`
 * (decision D1; API_DELETE_OWN=0 keeps it), which then re-checks the non-interference snapshot. `@local` rows run only
 * with TIER_KIND=local (proven local backend).
 *
 * Projects (the tier rules are ANDed into each, see utils/regression/projectFilters.ts):
 *   snapshot          guard proof, then the "before" snapshot of API-GEN-33 (tests/api/_run-setup.setup.ts, serial)
 *   non-interference  API-GEN-33, the teardown project of `snapshot`: runs after every other project, even failed ones
 *   gate              API-GEN-32 (`@gate`), the migration sentinels
 *   api-p1            `@p1` rows except the gate: they run whether the gate is green or not (they explain a red gate)
 *   api-rest          `@p2|@p3` rows: skipped when the gate fails
 * REG_PHASE=B selects only the `@phaseB` rows (snapshot and non-interference still run).
 */
const SETUP_FILES = /_run-setup\.setup\.ts$/;
const NON_INTERFERENCE = /API-GEN-33-non-interference\.api\.spec\.ts$/;

export default defineConfig({
    testDir: './tests/api',
    timeout: 60_000,
    expect: { timeout: 10_000 },
    fullyParallel: false,
    workers: 1,
    retries: 0,
    reporter: [
        ['line'],
        ['html', { open: 'never', outputFolder: 'playwright-report/api' }],
        ['junit', { outputFile: 'test-results/api-junit.xml' }],
    ],
    outputDir: 'test-results/api',
    globalTeardown: require.resolve('./utils/regression/runTeardown'),
    use: {
        baseURL: process.env.BASE_URL,
        ignoreHTTPSErrors: true,
        extraHTTPHeaders: { Accept: 'application/json' },
    },
    projects: withTierFilters(
        [
            { name: 'snapshot', testMatch: SETUP_FILES, teardown: 'non-interference' },
            { name: 'non-interference', testMatch: NON_INTERFERENCE },
            { name: 'gate', grep: /@gate\b/, testIgnore: NON_INTERFERENCE, dependencies: ['snapshot'],
                // A browser for the session sentinel; no forced JSON Accept header on page loads.
                use: { ...devices['Desktop Chrome'], extraHTTPHeaders: {} } },
            { name: 'api-p1', grep: /@p1\b/, grepInvert: /@gate\b/, testIgnore: NON_INTERFERENCE, dependencies: ['snapshot'] },
            { name: 'api-rest', grep: /@p2\b|@p3\b/, testIgnore: NON_INTERFERENCE, dependencies: ['gate'] },
        ],
        { infrastructure: ['snapshot', 'non-interference'] },
    ),
});
